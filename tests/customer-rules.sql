begin;
create temp table results(test text,passed boolean);
grant insert,select on results to authenticated,service_role;
do $$
declare u uuid:=gen_random_uuid();b uuid;s uuid;e uuid;other uuid;soon uuid;blocked boolean;start_at timestamptz:=date_trunc('minute',now()+interval '3 days');token text:=repeat('a',64);
begin
 insert into auth.users(id,email) values(u,u::text||'@example.invalid');
 perform set_config('request.jwt.claims',json_build_object('sub',u,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 insert into public.profiles(id,display_name) values(u,'QA Customer rules');
 insert into public.businesses(owner_id,slug,name) values(u,'qa-'||left(u::text,8),'QA Customer rules') returning id into b;
 update public.businesses set published=true,notice_minutes=0 where id=b;
 insert into public.services(business_id,name,price_cents,duration_minutes) values(b,'QA Service',1000,15) returning id into s;
 perform public.replace_availability(b,(select jsonb_agg(jsonb_build_object('weekday',d,'start_minute',0,'end_minute',1440)) from generate_series(0,6)d));
 soon:=public.reserve_appointment(b,s,date_trunc('minute',now()+interval '12 hours'),'QA Client','21999998888',gen_random_uuid(),token);
 e:=public.reserve_appointment(b,s,start_at,'QA Client','21999998888',gen_random_uuid(),token);
 other:=public.reserve_appointment(b,s,start_at+interval '1 hour','QA Client','21999998888',gen_random_uuid(),token);
 blocked:=false;begin perform public.replace_availability(b,'[{"weekday":1,"start_minute":900,"end_minute":800}]'::jsonb);exception when check_violation then blocked:=true;end;
 if not blocked or (select count(*) from public.availability where business_id=b)<>7 then raise exception 'invalid schedule lost original';end if;
 insert into results values('Invalid availability replacement preserves previous schedule',true);
 execute 'reset role';
 perform set_config('request.jwt.claims','{"role":"service_role"}',true);
 execute 'set local role service_role';
 blocked:=false;begin perform public.change_appointment(e,null,repeat('b',64));exception when insufficient_privilege then blocked:=true;end;
 if not blocked then raise exception 'wrong token allowed';end if;
 insert into results values('Wrong management token cannot change reservation',true);
 blocked:=false;begin perform public.change_appointment(soon,null,token);exception when invalid_parameter_value then blocked:=true;end;
 if not blocked then raise exception '24-hour cancellation deadline bypassed';end if;
 insert into results values('Customer cannot cancel inside 24-hour deadline',true);
 blocked:=false;begin perform public.change_appointment(soon,start_at+interval '2 hours',token);exception when invalid_parameter_value then blocked:=true;end;
 if not blocked then raise exception '24-hour rescheduling deadline bypassed';end if;
 insert into results values('Customer cannot reschedule inside 24-hour deadline',true);
 perform public.change_appointment(e,start_at+interval '2 hours',token);
 insert into results values('Valid token can reschedule before deadline',true);
 perform public.change_appointment(other,null,token);
 if not exists(select 1 from public.calendar_entries where id=other and status='canceled' and management_hash is null) then raise exception 'token not revoked';end if;
 insert into results values('Cancellation revokes management token',true);
 if not public.consume_limit(repeat('c',64),1,60) then raise exception 'first request rejected';end if;
 if public.consume_limit(repeat('c',64),1,60) then raise exception 'rate limit ignored';end if;
 insert into results values('Shared database rate limit rejects excess requests',true);
 execute 'reset role';
end $$;
select * from results;
rollback;
